from __future__ import annotations

import platform
import re
import shutil
from collections.abc import Iterable
from pathlib import Path

# Targets memsync shares with other tools. ~/.codex/AGENTS.md is also written by
# skill installers, so memsync owns only a marked block there, never the file.
SHARED_TARGET_LABELS = frozenset({"AGENTS.md"})

BLOCK_BEGIN = (
    "<!-- BEGIN memsync (regenerated from GLOBAL_MEMORY.md on every write; "
    "edit the source, not this block) -->"
)
BLOCK_END = "<!-- END memsync -->"
_BLOCK_RE = re.compile(
    r"<!-- BEGIN memsync\b[^\n]*?-->.*?<!-- END memsync -->[ \t]*(?:\r?\n)?",
    re.DOTALL,
)
# Whole-file outputs from earlier memsync versions start with one of these.
_LEGACY_PREFIXES = ("<!-- Generated by memsync",)


def sync(memory_path: Path, target_path: Path) -> None:
    """
    Keep target_path (CLAUDE.md) in sync with memory_path (GLOBAL_MEMORY.md).

    If target_path is already a symlink pointing at memory_path, it is left
    untouched. This supports setups where CLAUDE.md is intentionally symlinked
    to the synced memory file, and avoids a SameFileError on Windows where the
    copy path would otherwise copy a file onto itself.

    Mac/Linux: create a symlink. If a non-memsync file already exists at the
    target, back it up first (.pre-memsync.bak) so user data is never lost.

    Windows: copy. Symlinks require admin/Developer Mode; the copy is refreshed
    on every `memsync refresh`, so drift is acceptable in practice.
    """
    target_path.parent.mkdir(parents=True, exist_ok=True)

    # Already a correct symlink to the memory file: leave it as-is. Avoids the
    # SameFileError the Windows copy path would raise, and preserves an
    # intentionally symlinked CLAUDE.md so live updates flow through.
    if target_path.is_symlink() and target_path.resolve() == memory_path.resolve():
        return

    if platform.system() == "Windows":
        # A symlink pointing somewhere *else* must be cleared first. copy2 opens
        # the target for writing, which follows the link and overwrites whatever
        # it points at — so copying the projected core onto a CLAUDE.md still
        # symlinked to GLOBAL_MEMORY.md would destroy the canonical store.
        if target_path.is_symlink():
            target_path.unlink()
        shutil.copy2(memory_path, target_path)
        return

    # Mac / Linux: prefer a symlink.
    if target_path.is_symlink():
        target_path.unlink()
    elif target_path.exists():
        # Back up any existing real file before replacing it.
        target_path.rename(target_path.with_suffix(".pre-memsync.bak"))

    try:
        target_path.symlink_to(memory_path)
    except OSError:
        # Fallback to copy if symlink creation fails (e.g. cross-device).
        shutil.copy2(memory_path, target_path)


def is_synced(memory_path: Path, target_path: Path) -> bool:
    """
    Return True if target_path points at (or has the same content as) memory_path.
    """
    if not target_path.exists():
        return False

    if target_path.is_symlink():
        return target_path.resolve() == memory_path.resolve()

    # Windows copy path: compare content
    try:
        return target_path.read_bytes() == memory_path.read_bytes()
    except OSError:
        return False


def sync_many(memory_path: Path, target_paths: Iterable[Path]) -> None:
    """Sync one memory file into multiple instruction targets."""
    seen: set[str] = set()
    for target_path in target_paths:
        expanded = Path(target_path).expanduser()
        key = str(expanded).lower()
        if key in seen:
            continue
        seen.add(key)
        sync(memory_path, expanded)


def render_block(memory_path: Path) -> str:
    """The marked block memsync writes into a shared target."""
    content = memory_path.read_text(encoding="utf-8").rstrip("\r\n")
    return f"{BLOCK_BEGIN}\n{content}\n{BLOCK_END}\n"


def _is_legacy_whole_file(text: str, memory_path: Path) -> bool:
    """True when text is a whole-file copy an older memsync wrote."""
    stripped = text.lstrip("﻿")
    if stripped.startswith(_LEGACY_PREFIXES):
        return True
    try:
        return stripped == memory_path.read_text(encoding="utf-8")
    except OSError:
        return False


def sync_block(memory_path: Path, target_path: Path) -> None:
    """
    Keep memsync's marked block in target_path current, leaving the rest alone.

    Used for targets other tools also write (see SHARED_TARGET_LABELS). Always
    a real file, never a symlink, because a symlink would hand the whole file
    to memsync.

    - No file: write the block.
    - File with a block: replace the block in place.
    - File without a block: if it is a whole-file copy from an older memsync,
      replace it with the block; otherwise back it up (.pre-memsync.bak) and
      append the block after the existing content.
    - Symlink to the memory file (old Mac/Linux setup): replace with the block.
      Symlink elsewhere: update the file it points to, keeping the link.
    """
    target_path.parent.mkdir(parents=True, exist_ok=True)
    block = render_block(memory_path)

    if target_path.is_symlink():
        if target_path.resolve() == memory_path.resolve():
            target_path.unlink()
        else:
            target_path = target_path.resolve()

    if not target_path.exists():
        target_path.write_text(block, encoding="utf-8", newline="")
        return

    with open(target_path, encoding="utf-8", newline="") as f:
        existing = f.read()

    if _BLOCK_RE.search(existing):
        # A lambda, so backslashes in the memory text are not read as escapes.
        updated = _BLOCK_RE.sub(lambda _m: block, existing, count=1)
    elif _is_legacy_whole_file(existing, memory_path):
        updated = block
    else:
        backup = target_path.with_suffix(".pre-memsync.bak")
        shutil.copy2(target_path, backup)
        separator = "" if existing.endswith("\n") else "\n"
        updated = f"{existing}{separator}\n{block}"

    if updated != existing:
        target_path.write_text(updated, encoding="utf-8", newline="")


def is_block_synced(memory_path: Path, target_path: Path) -> bool:
    """True if target_path holds a memsync block matching memory_path."""
    if not target_path.exists():
        return False
    try:
        with open(target_path, encoding="utf-8", newline="") as f:
            text = f.read()
        match = _BLOCK_RE.search(text)
        return bool(match) and match.group(0).rstrip("\r\n") == render_block(
            memory_path
        ).rstrip("\n")
    except OSError:
        return False


def sync_targets(memory_path: Path, targets: Iterable[tuple[str, Path]]) -> None:
    """Sync labelled targets, using a marked block for shared ones."""
    seen: set[str] = set()
    for label, target_path in targets:
        expanded = Path(target_path).expanduser()
        key = str(expanded).lower()
        if key in seen:
            continue
        seen.add(key)
        if label in SHARED_TARGET_LABELS:
            sync_block(memory_path, expanded)
        else:
            sync(memory_path, expanded)


def target_is_synced(memory_path: Path, label: str, target_path: Path) -> bool:
    """The is_synced check that matches how sync_targets writes this label."""
    if label in SHARED_TARGET_LABELS:
        return is_block_synced(memory_path, target_path)
    return is_synced(memory_path, target_path)
